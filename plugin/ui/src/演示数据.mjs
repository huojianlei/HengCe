// 把录入表转成界面消费的结构：补齐期间、整数分金额、偏差率（基点）、方向与风险等级。
const rows = rawRows.map(([id, subject, module, department, departmentId, budgetYuan, actualYuan, decision, reason, cell]) => {
// 预算金额先转整数分，后续所有偏差都由整数分相减得出，不出现浮点误差。
  const budget = money(budgetYuan);
// 实际金额同上；两者统一单位后 variance 才有意义。
  const actual = money(actualYuan);
// 偏差 = 实际 − 预算（单位：分）。正负的经济含义随科目类型变化，由 direction 负责解释。
  const variance = actual - budget;
// 偏差率折算成整数基点（10000 基点 = 100%），四舍五入到整数，与后端「比率一律整数基点」的口径一致。
  const rate = Math.round(variance / budget * 10000);
// 方向判断：收入类超预算是好事，成本/费用/采购类超预算是坏事，两类指标判断相反。
// 采购作为独立管理视角也按「逆指标」处理（花钱多即不利），但它不参与利润口径的重复计算。
  const direction = (module === '收入' ? variance >= 0 : variance <= 0) ? 'favorable' : 'unfavorable';
// 只取不利偏差的绝对值参与风险分级：有利偏差再大也不该进高风险。
  const adverseRate = direction === 'unfavorable' ? Math.abs(rate) : 0;
// 返回结构固定为 id / 科目 / 模块 / 部门 / 期间 / 预算 / 实际 / 偏差 / 偏差率 / 风险 / 方向 / 判定 / 原因 / 来源。
  return {
// 主体与期间直接落在行上：切换部门筛选时不需要再回表关联，前端只做过滤。
    id, subject, module, department, departmentId, period: '2027-06', budget, actual,
// 初始风险阈值 3000 / 1500 基点与 config.tiers 保持一致；分析参数变更后由 业务桥.mjs 按新阈值重算。
    variance, rate, risk: adverseRate >= 3000 ? 'high' : adverseRate >= 1500 ? 'watch' : 'normal',
// decision 三取值（单环纠错 / 持续观察 / 双环纠错）是管理会计的整改层级判定，界面据此选标签颜色；
// source 拼成「工作簿 / 表名!单元格」形式，用户在界面上点开差异即可回到原始数据位置。
    direction, decision, reason, source: `演示-实时经营.xlsx / ${cell}`,
  };
});

