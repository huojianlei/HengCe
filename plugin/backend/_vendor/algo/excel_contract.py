# 位移配错的表现是整表取到空白，number() 会以 '缺失或非法数值' 报出具体格位。
OFFSETS = {'预算基础':0,'实时经营':60}
# 每个指标的科目编码在 P 列；工作簿内唯一且预算/实际共享相同编码。
def accounts():
    """生成科目注册表：三张费用表逐行 + 两张收入表各两行 + 税金及附加。

    编码规则：费用表 EXP{表序}.{行号:03}（第三张表的指标名统一归「其他主体费用」）；
    两张收入表 REV{表序}/COGS{表序}（行 33/36）；税金及附加 TAX。编码必须工作簿内
    唯一，预算与实际共享同一编码——否则勾稽与差异回溯都会错位，
    校验失败文案：'科目唯一编码不符：{表}!P{行}'。
    """
    result=[]
    for i,sheet in enumerate(SHEETS[6:9],1):  # SHEETS[6:9] = 销售/管理/蓝恐龙三张费用表
        for row,parent,leaf in EXPENSES:      # 行号 → 父类 → 叶子，逐行登记
            code=f'EXP{i}.{row:03}'           # 表序.行号三位：工作簿内唯一
            name=f'{"其他主体费用" if i==3 else sheet}/{parent}/{leaf}'  # 第三表统一归其他主体
            result.append(dict(sheet=sheet,row=row,column=3,code=code,name=name,module='费用模块',direction='成本类'))
    for i,sheet in enumerate(SHEETS[3:5],1):  # SHEETS[3:5] = 收入非主控/收入主控两张收入表
        result.extend([dict(sheet=sheet,row=33,column=3,code=f'REV{i}',name=f'营业收入/{sheet}',module='收入模块',direction='收入类'),
                       dict(sheet=sheet,row=36,column=3,code=f'COGS{i}',name=f'营业成本/{sheet}',module='成本模块',direction='成本类')])
    # 税金及附加只有科目一个，不参与表序编号：编码固定为 TAX
    result.append(dict(sheet='税金及附加',row=33,column=3,code='TAX',name='税金及附加',module='费用模块',direction='成本类'))
    return result

ACCOUNTS=accounts()  # 模块导入即固化注册表：顺序稳定，勾稽/回溯按它遍历
