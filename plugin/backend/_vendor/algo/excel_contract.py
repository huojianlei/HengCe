def col(index):
    """列号 → 列字母（1→A、26→Z、27→AA）；公式区域展开与表头定位共用。"""
    out=''
    while index:  # 26 进制折算，每轮拿最低一位
        index,n=divmod(index-1,26);out=chr(65+n)+out
    return out
