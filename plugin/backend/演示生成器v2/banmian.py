# -*- coding: utf-8 -*-
"""格位平移：把「分录」「摊销明细」从旧骨架的"功能区"（121 行 / O 列起）搬到 A1 起。

旧骨架把这两张表的数据放在 E121 起的功能区，左上角是 1.0.5 遗留的空白表头；
演示件不需要那套位置，直接平移到 A1，打开就能看到数据。

为什么需要这一层:
    参照档案（老师原件的结构骨架）中，「分录」「摊销明细」两张内部底稿表并不是从
    A1 开始排的，而是从 E121 / O121 起的"功能区"——上方和左侧留了 1.0.5 时期的空白
    表头与说明文字。演示件要的是"打开就能看到数据"，所以写盘前必须把这批格位整体
    平移回左上角；平移规则由本模块集中声明，写盘模块（xiechu.py）只负责按新格位赋值。

输入 / 输出契约:
    输入：旧格位字符串（如 ``'O122'``）+ 表名（``'分录'`` / ``'摊销明细'``）；
    输出：新格位字符串（如 ``'A1'``），不保留的格返回 ``None``。
    本模块是纯函数式的：不读写文件、不碰全局状态、不含随机数，同一个输入永远同一个输出。

口径:
    本模块只挪位置、不动数值，因此与"金额=分、比率=基点"的口径无关；被搬运的数值仍是
    整数分/整数基点原值，平移过程不引入任何四舍五入。

与其他模块的关系:
    ``_sheng_banshi.py`` 生成版式常量（旧格位 + 值），``xiechu.py`` 调 :func:`xin`
    把旧格位翻译成新格位后落盘；``PIAN_BIAO`` 声明哪两张表需要走平移。
"""
import re

#: 每张表的平移规则（行, 列）→ (新行, 新列)；None 表示丢弃该格
def _fan(ming, row, col):
    """核心平移函数：把 (表名, 旧行号, 旧列号) 映射成 (新行号, 新列号)。

    参数:
        ming: 表名，只有 ``'分录'`` / ``'摊销明细'`` 有专属规则，其余表原样返回。
        row:  1 基的旧行号（Excel 行号）。
        col:  1 基的旧列号（A=1、O=15 这种数字列号，由 :func:`_lie_hao` 换算而来）。

    返回:
        ``(新行, 新列)`` 二元组；``None`` 表示这一格是旧表头的残留、演示件不要。

    说明:
        下面每个分支都写着"哪一段行/列 → 哪一段行/列"，注释里的区间与代码里的
        比较式一一对应，改规则时两边要同步改，否则新格位会和版式常量对不上。
    """
    if ming == '分录':
        # 表头 122 → 1；明细 124-540 → 2-418；汇总 543-545 → 421-423；O..V → A..H
        # col < 15 即 O 列以左（A..N）全是旧骨架的表头/说明列，一律丢弃；
        # row < 122 即表头以上是空白区，同样丢弃（否则会覆盖新表头）。
        if col < 15 or row < 122:
            return None
        if row == 122:                     # 表头移到第 1 行
            return 1, col - 14
        return row - 122, col - 14          # 明细/汇总行整体上移 122 行、左移 14 列（O→A）
    if ming == '摊销明细':
        # 参数/月度区 31-36 行、B..O → 1-6 行、A..N
        # 这一段是摊销参数与月度摊销额（B 列是月份标签），平移后落在 A1 起的表头区。
        if 31 <= row <= 36 and col <= 15:
            return row - 30, col - 1
        # 台账区 121-130 → 8-17；矩阵区 132-142 → 19-29；O.. 列 → A..
        # 台账是逐笔摊销台账、矩阵是按月×科目的摊销额矩阵，两段都上移 113 行、左移 14 列；
        # 中间空出的 131 行（旧表里的分隔行）不保留，所以两段的偏移量相同即可。
        if 121 <= row <= 130 and col >= 15:
            return row - 113, col - 14
        if 132 <= row <= 142 and col >= 15:
            return row - 113, col - 14
        return None                         # 其余格（旧说明区、页脚）全部丢弃
    return row, col                         # 未登记规则的表：原样不动，交回调用方判断


def xin(ming, ref):
    """旧格位 → 新格位（返回 None 表示这格不保留）。

    参数:
        ming: 表名（如 ``'分录'``）。
        ref:  旧格位字符串，形如 ``'O122'``；大小写敏感，只认 ``[A-Z]+\\d+``。

    返回:
        新格位字符串（如 ``'A1'``），或 ``None``（垃圾格位 / 该格不保留）。

    异常边界:
        这里不做抛错：正则不匹配（``''``、``'12A'``、``'a1'`` 等）一律返回 ``None``，
        由调用方（写盘）静默跳过。这样单个脏格位不会中断整本演示件的生成。
    """
    m = re.fullmatch(r'([A-Z]+)(\d+)', ref)   # 拆成"列字母 + 行数字"，纯字母或纯数字都算脏格位
    if not m:
        return None
    lie, hang = m.group(1), int(m.group(2))    # lie 是列字母（如 'AE'），hang 是 1 基行号
    zhi = _fan(ming, hang, _lie_hao(lie))      # 先转成数字列号再查平移规则
    if zhi is None:
        return None
    return f'{_lie_ming(zhi[1])}{zhi[0]}'      # 数字列号再转回字母，拼成 Excel 格位


def _lie_hao(lie):
    """列字母 → 1 基数字列号（A=1、Z=26、AA=27）。

    用 26 进制逐位累加；注意这里没有 '0' 这个字符，所以不需要 A1 记号特有的偏移修正。
    """
    n = 0
    for ch in lie:
        n = n * 26 + (ord(ch) - 64)   # 'A' 的码位是 65，减 64 正好得到 1
    return n


def _lie_ming(n):
    """数字列号 → 列字母（1→'A'、26→'Z'、27→'AA'），:func:`_lie_hao` 的逆运算。

    Excel 列名是"没有 0 的 26 进制"，所以每轮先减 1 再取余，才能让 26 落在 'Z' 而不是 'A@'。
    n <= 0 时返回空串（脏输入不抛错，保持与 :func:`xin` 一致的静默策略）。
    """
    s = ''
    while n > 0:
        n, r = divmod(n - 1, 26)
        s = chr(65 + r) + s           # 余数 0..25 映射回 'A'..'Z'，逐位拼到左侧（低位在后）
    return s


#: 需要平移的表
PIAN_BIAO = ('分录', '摊销明细')        #: 写盘时按此元组判断要不要调 :func:`xin`
