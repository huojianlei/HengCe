            z[32] = sum((z[r] for r in (33, 34, 35, 36)), ZERO)
            z[37] = sum((z[r] for r in (38, 39, 40, 41, 42, 43)), ZERO)
            z[31] = z[32] + z[37]                                    # 其他综合收益税后净额
            z[44] = z[28] + z[31]                                    # 综合收益总额
