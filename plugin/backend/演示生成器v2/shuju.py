        # ---- 年末统一结平损益类科目（按分录账面余额结转到本年利润）----
        def yu_e(ke):
            """某科目截至当前行的账面余额（借 − 贷）。"""
            j = sum((self.biao[biao][f'S{r}'] for r in range(124, hang)
                     if self.biao[biao].get(f'Q{r}') == ke), ZERO)
            d = sum((self.biao[biao][f'T{r}'] for r in range(124, hang)
                     if self.biao[biao].get(f'R{r}') == ke), ZERO)
            return j - d

