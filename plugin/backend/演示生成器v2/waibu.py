# -*- coding: utf-8 -*-
"""外部两册数值模型：行业对标 / 经营变更（零公式、纯数值、名称走替换接口）。

口径（演示假设）：批次信息 15 键 + 基准指标 5 行 16 列 / 事件台账 2 行 15 列 /
科目影响 2 行 8 列，全部填数（无空格）；数值逐个避让老师原件数值黑名单。

这两册为什么单独一个模块:
    预算基础/实时经营共用 12 表、靠公式推导；行业对标与经营变更只有"批次信息+明细"
    两张小表、零公式，所以要填的格位是固定清单而不是推导出来的。把它单独拆出来，
    改版式时只动这里，不牵连 12 表那条主链路。

输入 / 输出契约:
    输入: seed（固定种子）+ tihuan（:func:`mingcheng.tihuan_biao` 的返回字典）。
    输出: ``{表名: {格位: 值}}``，格位是 'C2' 这种 Excel 写法，值是 str 或 Decimal。
          写盘模块（xiechu.py）直接逐格赋值，不做二次加工。
    本模块**不写文件**、不改全局状态，纯函数式；调用两次同参数得到完全相同的结果。

口径（金额/比率）:
    - 基准指标里的参考值带小数的百分数按"字符串"给（'38.62'，单位列写 '%'），
      不换成整数基点——这两册是"参考值展示"，不是计算输入，沿用参照档案的呈现方式。
    - 科目影响 E 列金额用 Decimal 并按分（FEN=Decimal('0.01')）量化，即"金额=分"口径，
      与 12 表主链路的整数分保持同一量纲，便于跨册核对。

标注纪律（硬性）:
    这两个册子的数全部是构造出来的演示参数，不得冒充真实统计值。所以每张表都显式写了
    '演示占位-v1'、'构造参考值'、'无真实样本'、'仅用于流程演示'、'固定种子 … 模拟'
    这类字段，B15 也专门写"演示数据，不代表真实情况"。改本模块时这些标注不许删。

异常边界:
    :func:`_bi_mian` 若 200 轮都避不开黑名单 → 抛 ValueError（不静默放行）；
    其余函数不抛错，输入缺失会得到 KeyError（说明调用方漏传 tihuan 键）。
"""
import random
from decimal import Decimal

from shuju import FEN, ming_zhong

#: 行业对标五指标：(编码, 名称, 参考值, 单位)
#: 参考值是"老师原件同位置数值的替换值"，只用来占住版式里的那一格；
#: 单位 '%' 表示这是比率类指标，呈现时不做基点换算（与 12 表内部口径区分开）。
HANGYE_ZB = (
    ('GROSS_MARGIN', '行业毛利率', '38.62', '%'),
    ('PROCUREMENT_COST_CHANGE', '采购成本变动率', '2.41', '%'),
    ('CAPACITY_UTILIZATION', '产能利用率', '76.35', '%'),
    ('EXPENSE_THRESHOLD', '费用阈值', '24.18', '%'),
    ('RAW_MATERIAL_INDEX', '原材料指数', '101.34', '%'),
)

#: 基准指标数据列 C..R（统计周期/参考值/单位/…/备注）
#: 16 列与下表 lie_zhi 的 16 个值按位置一一对应（zip 对不上会静默截断，改动两边要同步）。
ZB_LIE = ('C', 'D', 'E', 'F', 'G', 'H', 'I', 'J', 'K', 'L', 'M', 'N', 'O', 'P', 'Q', 'R')

#: 事件台账两行（A..O 十五字段，全部有值；两笔均"已批准"以便进入判定链）
#: 字段顺序按模板：事件号/类型/发生日/生效起/生效止/状态/决策机构/决策日/事由/经办/经办日/
#: 复核人/复核日/复核结论/依据。两笔都选费用类，是为了让"经营变更"在费用维度可验证。
SHI_JIAN = (
    ('EVT-2027-001', '采购条件变化', '2027-05-20', '2027-06', '2027-06', '已批准',
     '总经理办公会', '2027-05-21', '模拟供应商切换，差旅出行标准按新协议上调',
     '王经理', '2027-05-21', '李总监', '2027-05-25', '已批准', '演示依据 Demo-2027-016'),
    ('EVT-2027-002', '房租补充协议', '2027-05-18', '2027-06', '2027-12', '已批准',
     '总经理办公会', '2027-05-19', '模拟园区办公场地扩容，业务招待口径同步调整',
     '王经理', '2027-05-18', '李总监', '2027-05-22', '已批准', '演示协议 Demo-2027-018'),
)

#: 科目影响两行（A..H 八字段）：EXP1.021=销售费用/差旅费，EXP2.025=管理费用/业务招待费；
#: 影响期间落在事件生效区间内，均登记为结构性变更（双环/混合判定的确定性入口）。
#: E 列金额单位"元"、两位小数，写入前会经 :func:`_bi_mian` 按分量化并避让黑名单。
KE_MU = (
    ('EVT-2027-001', 'EXP1.021', '2027-06', '增加', '720.00', '元', '是', ''),
    ('EVT-2027-002', 'EXP2.025', '2027-06', '增加', '7100.00', '元', '是', ''),
)


def _bi_mian(v, bu=Decimal('0.37')):
    """小数避让黑名单。

    为什么要有: 参照档案里出现过的数值不能原样出现在演示件里（否则就成了"真数据"）。
    ``shuju.ming_zhong`` 给的是同一份黑名单，本函数只负责把一个候选数推到黑名单之外。

    参数:
        v:  候选值（str/Decimal 皆可），会先按分（FEN=0.01）量化成两位小数。
        bu: 每次避让的步长（默认 0.37，故意取非整数，避免一路踩回原来的尾数）。

    返回:
        Decimal，量化到分，且 ``ming_zhong`` 为假。

    异常边界:
        最多试 200 轮；仍命中黑名单就抛 ValueError（不静默放行，宁可生成失败）。
    """
    v = Decimal(v).quantize(FEN)          # 先按"金额=分"量化，保证两位小数
    for _ in range(200):
        if not ming_zhong(v):
            return v
        v = (v + bu).quantize(FEN)        # 命中就加步长再量化，保持两位小数
    raise ValueError(f'外部册数值无法避开黑名单：{v}')


def _pi_ci(seed, tihuan, zhong):
    """批次信息 B1..B15（B1 用中性版本串，不含任何真名）。

    参数:
        seed:   固定种子，写进 B15 供溯源。
        tihuan: :func:`mingcheng.tihuan_biao` 的返回，取其中的主体/情景/年度字段。
        zhong:  册别名（'行业对标' / '经营变更'），只用于 B1 的版本串。

    返回:
        dict[str, str]，键是 B1..B15。B7 固定 '月度'、B9 固定'模拟权责发生制'，
        都是演示假设；B15 必须带"演示数据，不代表真实情况"的标注，不得删。
    """
    return {
        'B1': f'标准/{zhong}/1.0.5',      # 版本串用中性写法，不带任何参照档案里的真名
        'B2': tihuan['主体编码'], 'B3': tihuan['主体名'], 'B4': tihuan['情景编码'],
        'B5': tihuan['情景'], 'B6': tihuan['年度'], 'B7': '月度',
        'B8': '演示占位-v1', 'B9': '模拟权责发生制', 'B10': '2027-01',
        'B11': '2027-06', 'B12': '无', 'B13': '无', 'B14': '占位',
        'B15': f'固定种子 {seed}；演示数据，不代表真实情况',   # 标注纪律：不许删
    }


def hangye_biao(seed, tihuan):
    """行业对标册：{表名: {格位: 值}}。

    版式：'批次信息' 15 行 + '基准指标' 5 行 × 16 列（C..R）。
    每行参考值 = 常量表里的参考值 + [-0.90, +0.90] 的随机浮动，再走 :func:`_bi_mian` 避让黑名单；
    浮动取整到分（rng.randrange(-90,91)/100），所以同一个 seed 必然得到同一组参考值。

    参数:
        seed:   固定种子。
        tihuan: 名称替换结果（提供年度/主体编码/情景编码）。

    返回:
        dict，键为表名，值为 {格位: 值}。其余 14 列（统计周期、单位、来源、备注等）
        全部填"构造/演示/无真实样本"类文案，确保被追问时不可能误读成真实统计。
    """
    rng = random.Random(f'{seed}|行业对标|v2')
    zhi = {'批次信息': _pi_ci(seed, tihuan, '行业对标'), '基准指标': {}}
    for i, (_, _, can, dan) in enumerate(HANGYE_ZB, 2):
        h = i
        jia = _bi_mian(Decimal(can) + Decimal(rng.randrange(-90, 91)) / 100)   # 参考值浮动
        # 16 个值按 ZB_LIE 的列顺序排列：统计周期/参考值/单位/口径/样本/出处/用途/来源/
        # 依据/数据日期/说明/主体编码/情景编码/是否演示/取值日/生成说明
        lie_zhi = (f'{tihuan["年度"]}-06', jia, dan, '构造参考值',
                   '影视投资示意（非统计总体）', '无真实样本',
                   '演示参数；不得用作真实阈值', '本地演示生成器',
                   '本地构造，无外部真实出处', f'{tihuan["年度"]}-06-30', '仅用于流程演示',
                   tihuan['主体编码'], tihuan['情景编码'], '是',
                   f'{tihuan["年度"]}-06-30', f'固定种子 {seed} 模拟')
        for x, v in zip(ZB_LIE, lie_zhi):
            zhi['基准指标'][f'{x}{h}'] = v
    return zhi


def biangeng_biao(seed, tihuan):
    """经营变更册：{表名: {格位: 值}}。

    版式：'批次信息' 15 行 + '事件台账' 2 行 × 15 列（A..O）+ '科目影响' 2 行 × 8 列（A..H）。
    台账与科目影响都是常量表，只有 E 列金额走 :func:`_bi_mian`（其余列是文本，无可避让）；
    H 列（备注）统一重写成"固定种子 … 模拟"，覆盖常量里的空串，保证每格都有标注。

    参数:
        seed:   固定种子，写进科目影响 H 列备注。
        tihuan: 名称替换结果（本函数只在批次信息里用到）。

    返回:
        dict，键为表名，值为 {格位: 值}；E 列值是 Decimal（量化到分），其余是 str。
    """
    zhi = {'批次信息': _pi_ci(seed, tihuan, '经营变更'), '事件台账': {}, '科目影响': {}}
    for i, hang in enumerate(SHI_JIAN, 2):
        for x, v in zip('ABCDEFGHIJKLMNO', hang):     # A..O 与 15 字段按位置对应
            zhi['事件台账'][f'{x}{i}'] = v
    for i, hang in enumerate(KE_MU, 2):
        for x, v in zip('ABCDEFGH', hang):
            # 只有 E 列（影响金额）是数值，需要避让黑名单；其余是编码/期间/方向/单位/标志
            zhi['科目影响'][f'{x}{i}'] = _bi_mian(v) if x == 'E' else v
        zhi['科目影响'][f'H{i}'] = f'固定种子 {seed} 模拟'   # H 列备注统一补演示标注
    return zhi
