# -*- coding: utf-8 -*-
"""名称替换接口：版式占位符 → 演示文本（唯一出入口，种子确定性）。

版式常量（banshi.py）里的文本一律带占位符：{主体一}/{主体二}/{项目一}/{主体名}…
运行到这里一次性渲染。要换成外部实现（数据库/接口/人工表），只需替换 tihuan_biao
一个函数，签名不变；其余代码一行不用动。

纪律：种子确定性（同种子同名字）；禁词自检（命中即抛错，绝不静默产出）。

为什么要有这一层:
    参照档案里带真实企业名、真项目名，这些名字绝不能出现在任何产物里。所以版式常量
    只写占位符，真名在"进产物之前"被本模块统一替换成虚构名称——替换点收敛到一个函数，
    审计时只需看这一处就能确认"有没有真名漏出去"。

输入 / 输出契约:
    输入: seed（整数，固定种子）、leibie（'预算基础'/'实时经营'）、qingjing（情景名）、
          niandu（年度）、可选 hangye/zhuti（强制指定行业词/主体名，供多行业回归用）。
    输出: dict[str, str]，键名固定 11 个（报表日/主体一/主体二/项目一/主体名/主体编码/
          情景编码/情景/年度/种子/类别），由写盘模块（xiechu.py）按格位填进批次信息表。

口径:
    本模块只产文本，不涉及金额与比率，因此与"金额=分、比率=基点"无关；但会原样透传
    种子到 '种子' 键，供产物溯源——这是"演示数据可复现"的证据链起点。

异常边界:
    任一替换文本命中禁词 → 抛 ValueError（中文报错带键名与值），不返回半成品；
    主体名生成循环理论上可能撞名，实际靠字号池×行业词池组合避让，不会死循环。
"""
import random

#: 字号池（双字僻字组合，避开现实企业与"衡/策/中/学"用字）
#: 取名口径：二字均为生僻字，读起来像企业字号但不指向任何真实公司；
#: 池子容量 12，乘以行业词 6 再抽两个不同主体，撞名概率可忽略。
ZIHAO = ('恒暻', '睿衍', '晟屿', '岚峙', '岱远', '泓翎', '屿棠',
         '峋瑞', '森屹', '洲衍', '宸屹', '汐衍')

#: 行业词池（一般企业报表适用行业）
#: 取的都是报表结构通用的行业，太专（如银行/保险）会影响模板科目口径。
HANGYE = ('智能制造', '数字科技', '供应链管理', '精密制造', '商贸实业', '信息技术')

#: 项目/剧名池（演示项目名，避开任何现实作品）
#: 对应参照档案里《少年派》那个位置——原名必须换掉，这里给的是虚构剧名。
XIANGMU = ('长夜将明', '云海之上', '山海谣', '星轨之外', '千灯引', '风起西洲', '清川行', '秋野纪')

#: 禁词（不得出现参照里的真名/项目名；"蓝恐龙"是单个企业的项目名，已从全链路剔除）
#: 命中即抛错，属于"宁可失败也不产出"的硬闸门；新增禁词直接往这个元组里加。
JIN_CI = ('衡策', '中学', '贰零壹陆', '蓝恐龙', '少年派')


def tihuan_biao(seed, leibie='预算基础', qingjing='基础情景', niandu=2027,
                hangye=None, zhuti=None):
    """占位符 → 演示文本。覆盖版式里出现的全部占位符。

    hangye / zhuti 可强制指定行业词与主体名（做多行业回归用），缺省随机。

    参数:
        seed:    固定种子（整数/字符串皆可），同一 seed 必得同一套名字。
        leibie:  '预算基础' 或 '实时经营'；只影响报表日（年末 12-31 vs 已结账月末 6-30）。
        qingjing: 情景名，原样透传到 '情景' 键，不做任何加工。
        niandu:  年度整数，用于拼报表日、主体编码与 '年度' 键。
        hangye:  可选，强制行业词；给了就固定用这个词，不再从 HANGYE 抽。
        zhuti:   可选，强制第一主体名；不以"有限公司"结尾时自动补后缀。

    返回:
        dict[str, str]，11 个键（报表日/主体一/主体二/项目一/主体名/主体编码/情景编码/
        情景/年度/种子/类别）。值都是字符串，写盘时按格位原样写入，不做类型转换。

    副作用:
        无文件读写、无全局变量改写。唯一的外部作用是可能抛 ValueError（命中禁词）。

    异常边界:
        禁词命中 → ValueError(f'替换文本含禁词 …')。这是有意为之：演示件一旦夹带真名，
        整批产物都要作废，所以宁可在生成阶段就炸掉。
    """
    # 种子串里带上 hangye/zhuti，保证"强制指定"时也是确定性的；分隔符用 '|' 避免字段歧义
    rng = random.Random(f'{seed}|名称替换|v2|防撞名|{hangye or ""}|{zhuti or ""}')
    # 两个主体名：字号池 × 行业词，互不相同
    zhuti_lie = []
    ci = 0
    while len(zhuti_lie) < 2:
        ci += 1
        hy = hangye or rng.choice(HANGYE)      # 强制行业优先，否则按种子池抽
        if ci == 1 and zhuti:
            ming = zhuti if zhuti.endswith('有限公司') else zhuti + '有限公司'
        else:
            # 第二主体始终"字号+行业+有限公司"；同一 rng 序列保证可复现
            ming = rng.choice(ZIHAO) + hy + '有限公司'
        if ming not in zhuti_lie:              # 两个主体不能同名，重名就再抽一轮
            zhuti_lie.append(ming)
    zhuti = zhuti_lie
    xiangmu = rng.choice(XIANGMU)
    # 报表日：预算基础=年末，实时经营=已结账月末
    # 实时经营取 6-30 是因为演示批次结账到 2027-06（见 waibu.py 的 B11 期末期间）。
    bao_biao_ri = (f'{niandu}年12月31日' if leibie == '预算基础'
                   else f'{niandu}年6月30日')
    biao = {
        '报表日': bao_biao_ri,
        '主体一': zhuti[0],              # 三表左列（原"贰零壹陆"位）
        '主体二': zhuti[1],              # 三表中列（原"蓝恐龙"位）
        '项目一': xiangmu,               # 三表"含《…》项目"位（原《少年派》）
        '主体名': zhuti[0],              # 九表元字段主体名
        '主体编码': f'ENT-{niandu}',     # 主体编码：年度级唯一，多批次同年度需配合情景编码区分
        '情景编码': 'S-BASE',            # 演示件固定基础情景编码（实时经营也沿用，仅作占位）
        '情景': qingjing,
        '年度': str(niandu),
        '种子': str(seed),               # 种子写进产物，是"可复现"的可见证据
        '类别': leibie,
    }
    # 全键扫描禁词：值与键都走一遍，命中即抛错（不写警告、不降级）
    for k, v in biao.items():
        for j in JIN_CI:
            if j in v:
                raise ValueError(f'替换文本含禁词 {j}：{k}={v}')
    return biao
